#include "lem_ipc.h"

void	init_shm(t_shm *shm)
{
	int		i;
	int		j;

	i = 0;
	while (i < MAP_SIZE)
	{
		j = 0;
		while (j < MAP_SIZE)
		{
			shm->map[i][j] = 0;
			j++;
		}
		i++;
	}
}
